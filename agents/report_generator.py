import os
from datetime import date
from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage, SystemMessage


class ReportGeneratorAgent:
    """
    Agent 4: Report Generator
    Takes outputs from Agents 1, 2, and 3 and writes a clean,
    structured clinical report a doctor could actually use.
    """

    def __init__(self, model="gpt-4o-mini"):
        api_key = os.getenv("OPENAI_API_KEY")
        if not api_key:
            raise ValueError("OPENAI_API_KEY not set.")
        self.llm = ChatOpenAI(model=model, temperature=0.2, api_key=api_key)

    def generate(self, path_result: dict, reasoning_chain, validation: dict) -> str:
        """
        Combines all agent outputs into one readable clinical report.
        """
        drug_a = reasoning_chain.drug_a
        drug_b = reasoning_chain.drug_b

        # Format shared targets
        targets_text = ""
        for t in path_result["shared_targets"][:5]:
            targets_text += f"  • {t['target_name']}\n"

        # Format reasoning steps
        steps_text = ""
        for step in reasoning_chain.steps:
            steps_text += f"  {step.step_number}. {step.claim}\n"

        system_prompt = """You are a clinical pharmacist writing a drug interaction
report for a prescribing physician. Write clearly, concisely, and professionally.
Use plain English where possible. Structure the report for quick reading."""

        user_prompt = f"""Write a clinical drug interaction report with the following data:

DRUGS: {drug_a} and {drug_b}
INTERACTION TYPE: {reasoning_chain.interaction_type}
SEVERITY: {reasoning_chain.severity}
MECHANISM: {reasoning_chain.mechanism_summary}

SHARED PROTEIN TARGETS:
{targets_text}

REASONING SUMMARY:
{steps_text}

CONFIDENCE: {validation['confidence_score']}/100 ({validation['evidence_quality']} evidence)
VALIDATED: {'Yes' if validation['validated'] else 'No — further review recommended'}
CLINICAL NOTE: {validation['notes']}

Write the report using these sections:
## Drug Interaction Report
## Summary
## Mechanism of Interaction
## Clinical Significance
## Recommendation
## Confidence & Limitations

Keep it under 300 words. Write for a busy doctor."""

        messages = [
            SystemMessage(content=system_prompt),
            HumanMessage(content=user_prompt)
        ]

        print(f"  Generating clinical report for {drug_a} + {drug_b}...")
        response = self.llm.invoke(messages)

        # Add header
        header = f"""
╔══════════════════════════════════════════════════════════╗
║           DRUG-DRUG INTERACTION REPORT                   ║
║  Generated by DDI-Agent  |  Date: {date.today()}         ║
╚══════════════════════════════════════════════════════════╝

"""
        return header + response.content


